// Command convbotan turns the SBox functions of Botan's
// src/lib/block/serpent/serpent_avx512/serpent_avx512.cpp (BSD-2-Clause, Jack
// Lloyd) into the Go table sbox512.go, so that nothing is retyped by hand.
// usage: convbotan serpent_avx512.cpp > sbox512.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

var (
	head = regexp.MustCompile(`^BOTAN_FORCE_INLINE void SBox([ED])(\d)\(`)
	stmt = regexp.MustCompile(`const SIMD_16x32 (\w+) = SIMD_16x32::ternary_fn<0x([0-9a-f]{2})>\((\w+), (\w+), (\w+)\);`)
)

func main() {
	f, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	var b strings.Builder
	b.WriteString("// Code generated by internal/convbotan from Botan 3.14.1\n")
	b.WriteString("// src/lib/block/serpent/serpent_avx512/serpent_avx512.cpp (BSD-2-Clause,\n")
	b.WriteString("// (C) 2023 Jack Lloyd). DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("// ternStep is one VPTERNLOGD: dst = table(a, b, c), the table's bit number\n")
	b.WriteString("// (a<<2 | b<<1 | c), as in _mm512_ternarylogic_epi32.\n")
	b.WriteString("type ternStep struct {\n\tdst     string\n\ttable   uint8\n\ta, b, c string\n}\n\n")
	b.WriteString("// ternSboxes maps sboxE0..sboxD7 to their steps; the outputs are o0..o3 and\n// the inputs a, b, c, d.\n")
	b.WriteString("var ternSboxes = map[string][]ternStep{\n")
	open := false
	n := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		l := sc.Text()
		if m := head.FindStringSubmatch(l); m != nil {
			if open {
				b.WriteString("\t},\n")
			}
			fmt.Fprintf(&b, "\t\"sbox%s%s\": {\n", m[1], m[2])
			open = true
			n++
			continue
		}
		if m := stmt.FindStringSubmatch(l); m != nil && open {
			fmt.Fprintf(&b, "\t\t{%q, 0x%s, %q, %q, %q},\n", m[1], m[2], m[3], m[4], m[5])
		}
	}
	if open {
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	if n != 16 {
		fmt.Fprintf(os.Stderr, "found %d S-boxes, want 16\n", n)
		os.Exit(1)
	}
	fmt.Print(b.String())
}
